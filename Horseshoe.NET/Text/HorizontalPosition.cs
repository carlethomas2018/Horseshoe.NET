namespace Horseshoe.NET.Text
{
    /// <summary>
    /// Enumeration that specifies horizontal alignment of text.
    /// </summary>
    public enum HorizontalPosition
    {
        /// <summary>
        /// No position specified. This is the default value and ususally refers to the right side.
        /// </summary>
        None,

        /// <summary>
        /// Left side
        /// </summary>
        Left,

        /// <summary>
        /// Center
        /// </summary>
        Center,

        /// <summary>
        /// Right side
        /// </summary>
        Right
    }
}
